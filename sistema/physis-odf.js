  var MANTER = /^(H1|H2|H3|H4|H5|H6|P|UL|OL|LI|DL|DT|DD|TABLE|THEAD|TBODY|TFOOT|TR|TH|TD|CAPTION|STRONG|B|EM|I|U|S|SMALL|SUB|SUP|CODE|PRE|BLOCKQUOTE|SPAN|DIV|SECTION|ARTICLE|FIGURE|FIGCAPTION|ABBR|TIME|MARK|DETAILS|SUMMARY|FIELDSET|LEGEND|BR|HR|Q|CITE|KBD|DEL|INS)$/;
  function esc(s) { return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;"); }
  function paraPublicar(raiz) {
    var partes = [], prom = [];
    (function anda(el) {
      Array.prototype.forEach.call(el.childNodes, function (n) {
        if (n.nodeType === 3) { partes.push(esc(n.nodeValue)); return; }
        if (n.nodeType !== 1) return;
        var tag = n.tagName.toUpperCase();
        if (/^(SCRIPT|STYLE|TEMPLATE|NOSCRIPT|BUTTON|NAV|DATALIST|IFRAME|OBJECT|EMBED)$/.test(tag) || some(n)) return;
        if (tag === "INPUT" || tag === "SELECT" || tag === "TEXTAREA") { var v = valorDe(n); if (v !== null && v !== "") partes.push("<span>" + esc(v) + "</span>"); return; }
        if (tag === "IMG" || tag === "SVG" || tag === "CANVAS") {
          var i = partes.length; partes.push("");
          prom.push(rasterizar(n).then(function (im) { if (im) partes[i] = '<img src="' + im.uri + '" alt="' + esc(im.alt || "") + '" width="' + im.largura_px + '" height="' + im.altura_px + '">'; }));
          return;
        }
        if (tag === "DETAILS" && !n.open) { var s = n.querySelector("summary"); if (s) partes.push("<p>" + esc(limpo(s.textContent)) + "</p>"); return; }
        if (!MANTER.test(tag)) { anda(n); return; }
        var a = "";
        ["colspan", "rowspan", "scope", "title", "lang", "dir", "data-paragrafo"].forEach(function (k) { if (n.hasAttribute(k)) a += " " + k + '="' + esc(n.getAttribute(k)) + '"'; });
        if (tag === "BR" || tag === "HR") { partes.push("<" + tag.toLowerCase() + a + ">"); return; }
        partes.push("<" + tag.toLowerCase() + a + ">"); anda(n); partes.push("</" + tag.toLowerCase() + ">");
      });
    })(raiz);
    return Promise.all(prom).then(function () { return partes.join(""); });
  }
