class _Limpador(HTMLParser):
    def __init__(self, rebaixar: bool, substituir: dict | None, img_max: int, imgs_max: int):
        super().__init__(convert_charrefs=True)
        self.saida: list[str] = []
        self.pilha: list[str] = []
        self.pular = 0                      # profundidade dentro de etiqueta descartada
        self.trocar = 0                     # profundidade dentro de parágrafo substituído
        self.rebaixar, self.substituir = rebaixar, substituir or {}
        self.img_max, self.imgs_max, self.imgs = img_max, imgs_max, 0
        self.avisos: set[str] = set()
        self.paragrafos: dict[str, dict] = {}
        self.abertos: list[str] = []        # âncoras abertas (para juntar o trecho de texto)
        self.ids: set[str] = set()
        self.seq = 0
        self.trocados: list[str] = []

    def _aviso(self, t):
        self.avisos.add(t)

    def _img(self, src: str) -> str | None:
        m = re.fullmatch(r"data:(image/(?:png|jpeg|gif|webp));base64,([A-Za-z0-9+/=\s]+)", src.strip(), re.I)
        if not m:
            self._aviso("imagem de fora ou em formato não aceito removida")
            return None
        b64 = re.sub(r"\s+", "", m.group(2))
        if len(b64) * 3 // 4 > self.img_max:
            self._aviso("imagem grande demais removida")
            return None
        try:
            dados = base64.b64decode(b64, validate=True)
        except (binascii.Error, ValueError):
            self._aviso("imagem corrompida removida")
            return None
        tipo = m.group(1).lower()
        if not _TIPOS_IMG[tipo](dados):
            self._aviso("imagem com tipo trocado removida")
            return None
        if self.imgs + len(dados) > self.imgs_max:
            self._aviso("limite total de imagens atingido; imagens a mais removidas")
            return None
        self.imgs += len(dados)
        return f"data:{tipo};base64,{b64}"

    def _atributos(self, tag: str, attrs) -> tuple[str, str | None]:
        saida, ancora = [], None
        for k, v in attrs:
            k = (k or "").lower()
            v = "" if v is None else str(v)
            if k.startswith("on") or k in ("style", "class", "id", "srcset", "formaction", "background", "xmlns", "nonce"):
                if k.startswith("on"):
                    self._aviso("atributos de evento (on…) removidos")
                continue
            if k == "data-paragrafo":
                if _ID.match(v) and v not in self.ids:
                    ancora = v
                continue
            if k in ("title", "lang"):
                saida.append(f'{k}="{_html.escape(v[:300], quote=True)}"')
            elif k == "dir" and v.lower() in ("ltr", "rtl", "auto"):
                saida.append(f'dir="{v.lower()}"')
            elif tag == "a" and k == "href":
                if re.fullmatch(r"#[A-Za-z0-9_-]{1,60}", v.strip()):
                    saida.append(f'href="{v.strip()}"')
                else:
                    self._aviso("links para fora do documento viraram texto")
            elif tag == "img" and k == "src":
                s = self._img(v)
                if s is None:
                    return "", "__sem_imagem__"
                saida.append(f'src="{s}"')
            elif tag == "img" and k == "alt":
                saida.append(f'alt="{_html.escape(v[:300], quote=True)}"')
            elif tag == "img" and k in ("width", "height") and re.fullmatch(r"\d{1,4}", v.strip()):
                saida.append(f'{k}="{v.strip()}"')
            elif tag in ("td", "th") and k in ("colspan", "rowspan") and re.fullmatch(r"\d{1,3}", v.strip()) and 1 <= int(v) <= 100:
                saida.append(f'{k}="{int(v)}"')
            elif tag == "th" and k == "scope" and v.lower() in ("row", "col", "rowgroup", "colgroup"):
                saida.append(f'scope="{v.lower()}"')
            elif tag in ("col", "colgroup") and k == "span" and re.fullmatch(r"\d{1,3}", v.strip()):
                saida.append(f'span="{int(v)}"')
            elif tag == "ol" and k == "start" and re.fullmatch(r"-?\d{1,6}", v.strip()):
                saida.append(f'start="{int(v)}"')
            elif tag == "ol" and k == "reversed":
                saida.append("reversed")
            elif tag == "li" and k == "value" and re.fullmatch(r"-?\d{1,6}", v.strip()):
                saida.append(f'value="{int(v)}"')
            elif tag == "time" and k == "datetime" and re.fullmatch(r"[0-9T:+\-. Z]{1,40}", v):
                saida.append(f'datetime="{v}"')
            elif tag == "details" and k == "open":
                saida.append("open")
            elif tag == "a" and k == "href":
                pass
            # o resto (src de fora, href, srcdoc, form*, xlink:*, data-* ...) cai fora
            elif k in ("src", "href", "action", "xlink:href", "srcdoc", "poster", "data"):
                self._aviso("endereços externos removidos")
        return (" " + " ".join(saida)) if saida else "", ancora

    def handle_starttag(self, tag, attrs):
        tag = tag.lower()
        if self.pular:
            if tag not in VAZIAS:
                self.pular += 1
            return
        if self.trocar:
            if tag not in VAZIAS:
                self.trocar += 1
            return
        if tag in DESCARTAR:
            if tag in ("script", "iframe", "object", "embed", "svg", "style", "frame", "applet"):
                self._aviso(f"<{tag}> removido")
            if tag not in VAZIAS:
                self.pular = 1
            return
        if tag not in PERMITIDAS:
            return                          # etiqueta desconhecida: some, o texto dentro fica
        if self.rebaixar and re.fullmatch(r"h[1-5]", tag):
            tag = "h" + str(int(tag[1]) + 1)
        elif tag == "h1":
            tag = "h2"
        attr, ancora = self._atributos(tag, attrs)
        if ancora == "__sem_imagem__":
            alt = next((v for k, v in attrs if (k or "").lower() == "alt" and v), "")
            self.saida.append(f'<span title="imagem removida">[{_html.escape(alt[:120] or "imagem removida")}]</span>')
            return
        self._fechar_implicitas(tag)
        if tag in ANCORAS:
            if not ancora:
                self.seq += 1
                ancora = f"p{self.seq}"
                while ancora in self.ids:
                    self.seq += 1
                    ancora = f"p{self.seq}"
            self.ids.add(ancora)
            self.paragrafos[ancora] = {"tag": tag, "trecho": ""}
            attr += f' data-paragrafo="{ancora}"'
        elif ancora:
            pass
        if tag in VAZIAS:
            self.saida.append(f"<{tag}{attr}>")
            return
        self.saida.append(f"<{tag}{attr}>")
        self.pilha.append(tag)
        self.abertos.append(ancora if tag in ANCORAS else "")
        if tag in ANCORAS and ancora in self.substituir and tag in TROCAVEIS:
            novo = str(self.substituir[ancora])
            self.saida.append(_html.escape(novo, quote=False))
            self.paragrafos[ancora]["trecho"] = re.sub(r"\s+", " ", novo).strip()[:200]
            self.trocados.append(ancora)
            self.trocar = 1

    # fins de etiqueta que o HTML deixa omitir (<li>a<li>b, <p>a<p>b, <td>a<td>b): fecha antes de abrir a próxima
    _FECHA = {"li": ({"li"}, {"ul", "ol"}), "dt": ({"dt", "dd"}, {"dl"}), "dd": ({"dt", "dd"}, {"dl"}),
              "tr": ({"tr"}, {"table", "thead", "tbody", "tfoot"}), "td": ({"td", "th"}, {"tr", "table"}),
              "th": ({"td", "th"}, {"tr", "table"}), "thead": ({"thead", "tbody", "tfoot"}, {"table"}),
              "tbody": ({"thead", "tbody", "tfoot"}, {"table"}), "tfoot": ({"thead", "tbody", "tfoot"}, {"table"})}
    _BLOCOS_P = {"p", "div", "ul", "ol", "dl", "table", "h2", "h3", "h4", "h5", "h6", "pre", "blockquote", "section", "article",
                 "figure", "hr", "details", "fieldset"}

    def _fechar_ate(self, alvos: set, limites: set) -> None:
        for i in range(len(self.pilha) - 1, -1, -1):
            t = self.pilha[i]
            if t in limites:
                return
            if t in alvos:
                while len(self.pilha) > i:
                    self.abertos.pop()
                    self.saida.append(f"</{self.pilha.pop()}>")
                return

    def _fechar_implicitas(self, tag: str) -> None:
        if tag in self._FECHA:
            self._fechar_ate(*self._FECHA[tag])
        if tag in self._BLOCOS_P:
            self._fechar_ate({"p"}, {"div", "li", "td", "th", "blockquote", "section", "article", "figure", "dd", "details", "fieldset", "table"})

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag.lower() not in VAZIAS:
            self.handle_endtag(tag)

    def handle_endtag(self, tag):
        tag = tag.lower()
        if self.pular:
            if tag not in VAZIAS:
                self.pular -= 1
            return
        if self.trocar:
            if tag not in VAZIAS:
                self.trocar -= 1
            if self.trocar:
                return
            # chegou ao fim do parágrafo trocado: fecha normalmente abaixo
        if self.rebaixar and re.fullmatch(r"h[1-5]", tag):
            tag = "h" + str(int(tag[1]) + 1)
        elif tag == "h1":
            tag = "h2"
        if tag not in PERMITIDAS or tag in VAZIAS or tag not in self.pilha:
            return
        while self.pilha:
            t = self.pilha.pop()
            self.abertos.pop()
            self.saida.append(f"</{t}>")
            if t == tag:
                break

    def handle_data(self, data):
        if self.pular or self.trocar:
            return
        self.saida.append(_html.escape(data, quote=False))
        texto = re.sub(r"\s+", " ", data)
        if texto.strip():
            for a in self.abertos:
                if a and len(self.paragrafos[a]["trecho"]) < 200:
                    self.paragrafos[a]["trecho"] = (self.paragrafos[a]["trecho"] + texto)[:200]

    def fim(self) -> str:
        self.close()
        while self.pilha:
            self.saida.append(f"</{self.pilha.pop()}>")
        for p in self.paragrafos.values():
            p["trecho"] = re.sub(r"\s+", " ", p["trecho"]).strip()
        return "".join(self.saida)


def sanitizar_html(html: str, rebaixar_titulos: bool = True, substituir: dict | None = None,
                   img_max: int = IMG_MAX, imgs_max: int = IMGS_MAX) -> dict:
    """Limpa o HTML para publicar. Devolve {"html", "paragrafos": {id: {"tag", "trecho"}}, "avisos": [...]}.
    Lista fechada de etiquetas/atributos; o que não está nela sai. Rodar de novo no resultado não muda nada
    (com rebaixar_titulos=False). `substituir={id: texto}` troca o conteúdo daquele parágrafo (sugestão aceita)."""
    if not isinstance(html, str):
        raise ValueError("html precisa ser texto")
    if len(html) > HTML_MAX:
        raise ValueError("documento grande demais")
    lp = _Limpador(rebaixar_titulos, substituir, img_max, imgs_max)
    lp.feed(html)
    saida = lp.fim()
    return {"html": saida, "paragrafos": lp.paragrafos, "avisos": sorted(lp.avisos), "trocados": lp.trocados}


