# ── células de planilha: texto pt-BR vira número, moeda, porcentagem ou data ──
_NUM = re.compile(r"^(?P<sinal>[+\-−])?\s*(?P<moeda>R\$\s*)?(?P<num>\d{1,3}(?:\.\d{3})+(?:,\d+)?|\d+(?:,\d+)?)\s*(?P<pct>%)?$")
_DATA = re.compile(r"^(\d{2})/(\d{2})/(\d{4})$|^(\d{4})-(\d{2})-(\d{2})$")


def interpretar_celula(v) -> tuple[str, object]:
    """('float'|'currency'|'percentage'|'date'|'boolean'|'string'|'vazio', valor).
    "1.234,56" -> 1234.56 · "R$ 10,00" -> moeda 10.0 · "12,5%" -> 0.125 · "15/11/2026" -> data.
    Fica texto: CEP/código com zero à esquerda, "1.5" (ambíguo em pt-BR), qualquer coisa com letra."""
    if v is None or (isinstance(v, str) and v.strip() == ""):
        return "vazio", ""
    if isinstance(v, bool):
        return "boolean", v
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return ("float", float(v)) if v == v and v not in (float("inf"), float("-inf")) else ("string", str(v))
    if isinstance(v, _dt.datetime):
        return "date", v.replace(microsecond=0).isoformat()
    if isinstance(v, _dt.date):
        return "date", v.isoformat()
    s = re.sub(r"\s+", " ", str(v)).strip().replace(" ", " ")
    m = _DATA.match(s)
    if m:
        d, mo, a = (m.group(1), m.group(2), m.group(3)) if m.group(1) else (m.group(6), m.group(5), m.group(4))
        try:
            return "date", _dt.date(int(a), int(mo), int(d)).isoformat()
        except ValueError:
            return "string", s
    m = _NUM.match(s)
    if not m:
        return "string", s
    digitos = re.sub(r"\D", "", m.group("num").split(",")[0])
    if len(digitos) > 1 and digitos.startswith("0") and "," not in m.group("num"):
        return "string", s                       # CEP, código, matrícula
    n = float(m.group("num").replace(".", "").replace(",", "."))
    if m.group("sinal") in ("-", "−"):
        n = -n
    if m.group("pct"):
        return "percentage", n / 100
    if m.group("moeda"):
        return "currency", n
    return "float", n


def _num_txt(n: float) -> str:
    """Valor de office:value: sem notação científica, ponto decimal."""
    t = repr(float(n))
    if "e" in t or "E" in t:
        t = f"{n:.15f}".rstrip("0").rstrip(".")
    return t[:-2] if t.endswith(".0") else t


