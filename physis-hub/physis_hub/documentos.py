def odt(titulo: str, blocos: list[dict], sistema: str = "Sistema Physis", logo_png: bytes | None | bool = None,
        idioma: str = "pt-BR", quando: _dt.datetime | None = None, marca_dagua: bool = True,
        fonte_titulo: str = "Fraunces", fonte_texto: str = "Inter") -> bytes:
    """Texto ODF (.odt). Blocos (mesmo modelo do physis-odf.js):
         {"h": 1..6, "t": "Título"}                       (nível de tópico; 4-6 saem como 3)
         {"t": "Parágrafo"}  ·  {"t": "item", "lista": True | "ol"}
         {"tabela": {"cab": [...], "linhas": [[...], ...], "legenda": "..."}}
         {"imagem": {"png": bytes, "alt": "...", "largura_px": 800, "altura_px": 400, "svg": bytes opcional}}
       logo_png: bytes do PNG; None usa web/app/icone-192.png se existir; False tira o logo."""
    quando = quando or _dt.datetime.now()
    T = _textos(idioma)
    if logo_png is None:
        logo_png = LOGO_PADRAO.read_bytes() if LOGO_PADRAO.is_file() else False
    figuras: list[tuple[str, bytes, str]] = []
    corpo = [f'<text:p text:style-name="Title">{_t(titulo)}</text:p>',
             f'<text:p text:style-name="Subtitle">{_x(T["gerado"])} {_x(_quando_txt(quando, idioma))} · {_x(AUTOR)}</text:p>']
    lista_aberta = None
    ntab = nimg = 0
    for b in blocos or []:
        tipo_lista = (b.get("lista") and ("ol" if b.get("lista") == "ol" else "ul")) or None
        if lista_aberta and tipo_lista != lista_aberta:
            corpo.append("</text:list>")
            lista_aberta = None
        if tipo_lista:
            if not lista_aberta:
                corpo.append(f'<text:list text:style-name="{"Lista_20_Numerada" if tipo_lista == "ol" else "Lista_20_Physis"}">')
                lista_aberta = tipo_lista
            corpo.append(f'<text:list-item><text:p text:style-name="Lista">{_t(b.get("t"))}</text:p></text:list-item>')
        elif b.get("h"):
            n = max(1, min(3, int(b["h"])))
            corpo.append(f'<text:h text:style-name="Heading_20_{n}" text:outline-level="{n}">{_t(b.get("t"))}</text:h>')
        elif b.get("tabela"):
            tb = b["tabela"]
            cab, linhas = list(tb.get("cab") or []), [list(l) for l in (tb.get("linhas") or [])]
            ncol = max([len(cab)] + [len(l) for l in linhas] + [1])
            ntab += 1
            cel = lambda v, est, pst: (f'<table:table-cell table:style-name="{est}" office:value-type="string">'
                                       f'<text:p text:style-name="{pst}">{_t("" if v is None else v)}</text:p></table:table-cell>')
            s = [f'<table:table table:name="{_x(T["tabela"])}{ntab}" table:style-name="Tab">'
                 f'<table:table-column table:style-name="TabCol" table:number-columns-repeated="{ncol}"/>']
            if cab:
                s.append("<table:table-header-rows><table:table-row>" + "".join(
                    cel(cab[i] if i < len(cab) else "", "TabCab", "Tabela_20_cabecalho") for i in range(ncol)) + "</table:table-row></table:table-header-rows>")
            for l in linhas:
                s.append("<table:table-row>" + "".join(cel(l[i] if i < len(l) else "", "TabCel", "Tabela_20_texto") for i in range(ncol)) + "</table:table-row>")
            if not cab and not linhas:
                s.append("<table:table-row>" + cel("", "TabCel", "Tabela_20_texto") * ncol + "</table:table-row>")
            s.append("</table:table>")
            corpo.append("".join(s))
            if tb.get("legenda"):
                corpo.append(f'<text:p text:style-name="Legenda">{_t(tb["legenda"])}</text:p>')
        elif b.get("imagem"):
            im = b["imagem"]
            png = im.get("png") or b""
            tam = _png_tamanho(png) if png else None
            if not tam:
                continue                          # imagem que não é PNG: fica de fora em vez de quebrar o arquivo
            nimg += 1
            lpx, apx = int(im.get("largura_px") or tam[0]), int(im.get("altura_px") or tam[1])
            larg = min(17.0, max(1.0, lpx * 2.54 / 96))
            alt_cm = larg * apx / max(1, lpx)
            if alt_cm > 22:
                larg, alt_cm = larg * 22 / alt_cm, 22.0
            nome = f"Pictures/imagem{nimg}.png"
            figuras.append((nome, png, "image/png"))
            imagens = ""
            if im.get("svg"):
                nsvg = f"Pictures/imagem{nimg}.svg"
                figuras.append((nsvg, im["svg"] if isinstance(im["svg"], bytes) else str(im["svg"]).encode("utf-8"), "image/svg+xml"))
                imagens += (f'<draw:image xlink:href="{nsvg}" xlink:type="simple" xlink:show="embed" xlink:actuate="onLoad" draw:mime-type="image/svg+xml"/>')
            imagens += f'<draw:image xlink:href="{nome}" xlink:type="simple" xlink:show="embed" xlink:actuate="onLoad" draw:mime-type="image/png"/>'
