PDFA_FILTRO = 'pdf:writer_pdf_Export:{"SelectPdfVersion":{"type":"long","value":"2"},"UseTaggedPDF":{"type":"boolean","value":"true"}}'


def soffice_programa(programa: str | None = None) -> str | None:
    import shutil
    return programa or os.environ.get("PHYSIS_SOFFICE") or shutil.which("soffice") or shutil.which("libreoffice")


def converter_pdfa(odf: bytes, programa: str | None = None, tempo: float = 120.0, extensao: str = "odt") -> dict:
    """ODT/ODS -> PDF/A-2b (PDF 1.7, fontes embutidas, XMP) com o LibreOffice: `soffice --headless
    --convert-to 'pdf:writer_pdf_Export:{"SelectPdfVersion":...2}'`. Sem o programa: código 501."""
    import subprocess
    import tempfile
    exe = soffice_programa(programa)
    if not exe:
        return {"ok": False, "codigo": 501, "erro": "o LibreOffice (soffice) não está instalado neste servidor; "
                "baixe em ODT e exporte em PDF/A pelo LibreOffice, ou instale-o (docs/EXPORTACAO.md)"}
    if not odf.startswith(b"PK\x03\x04") or extensao not in ("odt", "ods"):
        return {"ok": False, "codigo": 400, "erro": "o arquivo não é um ODT/ODS"}
    with tempfile.TemporaryDirectory() as d:
        ent = Path(d) / f"documento.{extensao}"
        ent.write_bytes(odf)
        perfil = Path(d) / "perfil"                # perfil próprio: não briga com um LibreOffice aberto
        cmd = [exe, f"-env:UserInstallation={perfil.as_uri()}", "--headless", "--norestore", "--convert-to",
               PDFA_FILTRO.replace("writer_pdf_Export", "calc_pdf_Export") if extensao == "ods" else PDFA_FILTRO,
               "--outdir", str(d), str(ent)]
        try:
            p = subprocess.run(cmd, capture_output=True, timeout=tempo)
        except (OSError, subprocess.TimeoutExpired) as exc:
            return {"ok": False, "codigo": 500, "erro": f"a conversão não terminou: {exc}"}
        sai = Path(d) / "documento.pdf"
        if not sai.is_file() or sai.stat().st_size == 0:
            msg = (p.stderr or b"").decode("utf-8", "replace").strip().splitlines()[-1:] or ["sem detalhe"]
            return {"ok": False, "codigo": 422, "erro": "o LibreOffice não gerou o PDF (" + msg[0][:160] + ")"}
        pdf = sai.read_bytes()
    return {"ok": True, "pdf": pdf, "pdfa": b"pdfaid:part" in pdf}


