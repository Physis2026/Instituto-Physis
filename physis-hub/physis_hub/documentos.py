def _limpo(t, n: int) -> str:
    return re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", "", str(t or "")).strip()[:n]


class Documentos:
    """Documentos publicados para comentários. Guarda no mesmo SQLite do hub (hub._db, hub._trava)."""

    def __init__(self, hub, relogio_limite=time.monotonic):
        self.hub = hub
        with hub._trava:
            hub._db.executescript(TABELAS)
            hub._db.commit()
        v = seg.ler_limite(os.environ.get(LIMITE_CONVITE[0]), LIMITE_CONVITE[1])
        self.lim = seg.Limitador(v[0], v[1], relogio_limite) if v else None
        v = seg.ler_limite(os.environ.get(LIMITE_CONVITE_ERRO[0]), LIMITE_CONVITE_ERRO[1])
        self.lim_erro = seg.Limitador(v[0], v[1], relogio_limite) if v else None

    # ── quem está pedindo ──
    def ator(self, doc_id: str, conta: dict | None, convite: str | None, ip: str = "") -> tuple[dict | None, tuple | None]:
        """(ator, None) ou (None, (código, json)). Equipe com sessão vem primeiro; senão, convite válido."""
        if conta and seg.pode(conta, seg.EQUIPE):
            return {"tipo": "equipe", "ref": conta["usuario"], "nome": conta.get("nome") or conta["usuario"],
                    "direcao": seg.pode(conta, seg.DIRECAO), "pode_comentar": True}, None
        if convite:
            espera = self.lim.tentar(ip or "?") if self.lim else 0.0          # todo pedido com convite gasta uma ficha
            if espera > 0:
                n = max(1, int(espera + 0.999))
                return None, (429, {"ok": False, "erro": f"muitos pedidos; tente de novo em {n} s", "espera": n})
            c = self._convite_valido(doc_id, convite)
            if c:
                return c, None
            # convite errado, vencido ou revogado: balde mais curto; esgotado, responde 429 (chutar códigos não compensa)
            espera = self.lim_erro.tentar(ip or "?") if self.lim_erro else 0.0
            if espera > 0:
                n = max(1, int(espera + 0.999))
                return None, (429, {"ok": False, "erro": f"muitos pedidos; tente de novo em {n} s", "espera": n})
            return None, (403, {"ok": False, "convite": False, "erro": "Este link de revisão não vale mais (vencido, revogado ou errado). Peça um novo à Physis."})
        if conta:
            return None, (403, {"ok": False, "erro": "o seu papel não permite esta ação"})
        return None, (401, {"ok": False, "erro": "entre com usuario e senha", "login": True})

    def _convite_valido(self, doc_id: str, token: str) -> dict | None:
        if not token or len(token) > 200:
            return None
        r_ = seg.resumo(token)
        with self.hub._trava:
            agora = self.hub.relogio()
            r = self.hub._db.execute(
                "SELECT c.id, c.nome, c.pode_comentar, c.resumo FROM doc_convite c JOIN doc d ON d.id=c.doc_id "
                "WHERE c.resumo=? AND c.doc_id=? AND c.revogado IS NULL AND c.expira>? AND d.arquivado IS NULL",
                (r_, doc_id, agora)).fetchone()
            if not r or not seg.iguais(r[3], r_):
                return None
            self.hub._db.execute("UPDATE doc_convite SET acessos=acessos+1, usado=COALESCE(usado, ?) WHERE id=?", (agora, r[0]))
            self.hub._db.commit()
        return {"tipo": "convite", "ref": str(r[0]), "nome": r[1], "direcao": False, "pode_comentar": bool(r[2])}

    # ── publicar e versões ──
    def publicar(self, ator: dict, titulo: str, html: str, origem: str = "", nota: str = "") -> dict:
        if ator.get("tipo") != "equipe":
            return {"ok": False, "codigo": 403, "erro": "só a equipe publica"}
        titulo = _limpo(titulo, 200)
        if not titulo:
            return {"ok": False, "codigo": 400, "erro": "falta o título"}
        try:
            limpo = sanitizar_html(html or "")
        except ValueError as e:
            return {"ok": False, "codigo": 413 if "grande" in str(e) else 400, "erro": str(e)}
        if not limpo["paragrafos"] and not re.sub(r"<[^>]+>", "", limpo["html"]).strip():
            return {"ok": False, "codigo": 400, "erro": "não há conteúdo para publicar"}
        ident = secrets.token_urlsafe(18)
        with self.hub._trava:
            agora = self.hub.relogio()
            self.hub._db.execute("INSERT INTO doc(id,titulo,origem,criado_por,criado_em,atualizado_em,versao_atual) VALUES(?,?,?,?,?,?,1)",
                                 (ident, titulo, _limpo(origem, 200), ator["ref"], agora, agora))
            self._gravar_versao(ident, 1, limpo, ator, nota, agora)
            self.hub.registrar("documento", ator["ref"], {"o_que": "publicado", "doc": ident[:8], "titulo": titulo})
            self.hub._db.commit()
        return {"ok": True, "id": ident, "versao": 1, "avisos": limpo["avisos"], "link": f"/documento/{ident}"}

    def _gravar_versao(self, doc_id, versao, limpo, ator, nota, agora):
        self.hub._db.execute("INSERT INTO doc_versao(doc_id,versao,html,resumo,paragrafos,avisos,nota,criado_por,criado_em) VALUES(?,?,?,?,?,?,?,?,?)",
                             (doc_id, versao, limpo["html"], hashlib.sha256(limpo["html"].encode("utf-8")).hexdigest(),
                              json.dumps(limpo["paragrafos"], ensure_ascii=False), json.dumps(limpo["avisos"], ensure_ascii=False),
                              _limpo(nota, 500), ator["ref"], agora))

    def nova_versao(self, doc_id: str, ator: dict, html: str, nota: str = "", _ja_limpo: dict | None = None) -> dict:
        if ator.get("tipo") != "equipe":
            return {"ok": False, "codigo": 403, "erro": "só a equipe publica versões"}
        try:
            limpo = _ja_limpo or sanitizar_html(html or "")
        except ValueError as e:
            return {"ok": False, "codigo": 413 if "grande" in str(e) else 400, "erro": str(e)}
        with self.hub._trava:
            d = self.hub._db.execute("SELECT versao_atual, arquivado FROM doc WHERE id=?", (doc_id,)).fetchone()
            if not d:
                return {"ok": False, "codigo": 404, "erro": "documento não encontrado"}
            if d[1] is not None:
                return {"ok": False, "codigo": 409, "erro": "documento arquivado"}
            atual = self.hub._db.execute("SELECT resumo FROM doc_versao WHERE doc_id=? AND versao=?", (doc_id, d[0])).fetchone()
            if atual and atual[0] == hashlib.sha256(limpo["html"].encode("utf-8")).hexdigest():
                return {"ok": True, "versao": d[0], "igual": True, "avisos": limpo["avisos"]}
            agora, v = self.hub.relogio(), d[0] + 1
            self._gravar_versao(doc_id, v, limpo, ator, nota, agora)
            self.hub._db.execute("UPDATE doc SET versao_atual=?, atualizado_em=? WHERE id=?", (v, agora, doc_id))
            self.hub.registrar("documento", ator["ref"], {"o_que": "nova versão", "doc": doc_id[:8], "versao": v})
            self.hub._db.commit()
        return {"ok": True, "versao": v, "avisos": limpo["avisos"]}

    def listar(self) -> list[dict]:
        with self.hub._trava:
            linhas = self.hub._db.execute(
                "SELECT d.id, d.titulo, d.origem, d.criado_por, d.criado_em, d.atualizado_em, d.versao_atual, d.arquivado, "
                "(SELECT COUNT(*) FROM doc_comentario c WHERE c.doc_id=d.id AND c.pai IS NULL AND c.estado='aberto' AND c.apagado=0) "
                "FROM doc d ORDER BY d.atualizado_em DESC").fetchall()
        return [{"id": i, "titulo": t, "origem": o, "criado_por": cp, "criado_em": ce, "atualizado_em": ae, "versao": v,
                 "arquivado": a is not None, "abertos": n, "link": f"/documento/{i}"} for i, t, o, cp, ce, ae, v, a, n in linhas]

    def ver(self, doc_id: str, ator: dict, versao: int | None = None) -> dict:
        with self.hub._trava:
            d = self.hub._db.execute("SELECT titulo, origem, criado_em, atualizado_em, versao_atual, arquivado FROM doc WHERE id=?", (doc_id,)).fetchone()
            if not d:
                return {"ok": False, "codigo": 404, "erro": "documento não encontrado"}
            v = d[4] if versao is None else versao
            r = self.hub._db.execute("SELECT html, paragrafos, nota, criado_por, criado_em, avisos FROM doc_versao WHERE doc_id=? AND versao=?", (doc_id, v)).fetchone()
            if not r:
                return {"ok": False, "codigo": 404, "erro": "versão não encontrada"}
            versoes = self.hub._db.execute("SELECT versao, nota, criado_em FROM doc_versao WHERE doc_id=? ORDER BY versao", (doc_id,)).fetchall()
        return {"ok": True, "id": doc_id, "titulo": d[0], "origem": d[1], "criado_em": d[2], "atualizado_em": d[3],
                "versao_atual": d[4], "versao": v, "arquivado": d[5] is not None, "html": r[0], "paragrafos": json.loads(r[1]),
                "nota": r[2], "avisos": json.loads(r[5]) if ator["tipo"] == "equipe" else [],
                "versoes": [{"versao": a, "nota": b, "criado_em": c} for a, b, c in versoes],
                "eu": {"nome": ator["nome"], "tipo": ator["tipo"], "pode_comentar": ator["pode_comentar"] and d[5] is None,
                       "pode_resolver": ator["tipo"] == "equipe", "pode_convidar": ator["tipo"] == "equipe"},
                "comentarios": self.comentarios(doc_id, ator)}

    # ── comentários ──
    def comentarios(self, doc_id: str, ator: dict) -> list[dict]:
        with self.hub._trava:
            linhas = self.hub._db.execute(
                "SELECT id, versao, paragrafo, pai, autor, autor_tipo, autor_ref, texto, sugestao, sugestao_estado, estado, "
                "criado_em, editado_em, resolvido_por, resolvido_em, apagado FROM doc_comentario WHERE doc_id=? ORDER BY id", (doc_id,)).fetchall()
        out = []
        for (i, v, p, pai, autor, at, ar, texto, sug, sest, est, ce, ee, rp, re_, ap) in linhas:
            meu = at == ator["tipo"] and ar == ator["ref"]
            out.append({"id": i, "versao": v, "paragrafo": p, "pai": pai, "autor": autor, "autor_tipo": at, "meu": meu,
                        "texto": "" if ap else texto, "sugestao": None if ap else sug, "sugestao_estado": sest, "estado": est,
                        "criado_em": ce, "editado_em": ee, "resolvido_por": rp, "resolvido_em": re_, "apagado": bool(ap),
                        "pode_editar": meu and not ap, "pode_apagar": (meu or ator.get("direcao")) and not ap})
        return out

    def comentar(self, doc_id: str, ator: dict, d: dict) -> dict:
        if not ator.get("pode_comentar"):
            return {"ok": False, "codigo": 403, "erro": "este acesso só permite ler"}
        texto = _limpo(d.get("texto"), TEXTO_MAX)
        sugestao = _limpo(d.get("sugestao"), TEXTO_MAX) or None
        if not texto and not sugestao:
            return {"ok": False, "codigo": 400, "erro": "escreva o comentário"}
        with self.hub._trava:
            doc = self.hub._db.execute("SELECT versao_atual, arquivado FROM doc WHERE id=?", (doc_id,)).fetchone()
            if not doc:
                return {"ok": False, "codigo": 404, "erro": "documento não encontrado"}
            if doc[1] is not None:
                return {"ok": False, "codigo": 409, "erro": "documento arquivado: comentários fechados"}
            pai = d.get("pai")
            if pai is not None:
                try:
                    pai = int(pai)
                except (TypeError, ValueError):
                    return {"ok": False, "codigo": 400, "erro": "resposta a um comentário inválido"}
                r = self.hub._db.execute("SELECT versao, paragrafo, pai FROM doc_comentario WHERE id=? AND doc_id=?", (pai, doc_id)).fetchone()
                if not r:
                    return {"ok": False, "codigo": 404, "erro": "comentário não encontrado"}
                versao, paragrafo = r[0], r[1]
                pai = r[2] or pai                        # resposta de resposta vai para a mesma conversa
                sugestao = None                          # sugestão só no comentário que abre a conversa
            else:
                try:
                    versao = int(d.get("versao") or doc[0])
                except (TypeError, ValueError):
                    return {"ok": False, "codigo": 400, "erro": "versão inválida"}
                paragrafo = str(d.get("paragrafo") or "geral")
                r = self.hub._db.execute("SELECT paragrafos FROM doc_versao WHERE doc_id=? AND versao=?", (doc_id, versao)).fetchone()
                if not r:
                    return {"ok": False, "codigo": 404, "erro": "versão não encontrada"}
                if paragrafo != "geral" and paragrafo not in json.loads(r[0]):
                    return {"ok": False, "codigo": 400, "erro": "parágrafo não existe nesta versão"}
                if sugestao and (paragrafo == "geral" or json.loads(r[0])[paragrafo]["tag"] not in TROCAVEIS):
                    return {"ok": False, "codigo": 400, "erro": "sugestão de texto só em parágrafo, título ou item"}
            agora = self.hub.relogio()
            cur = self.hub._db.execute(
                "INSERT INTO doc_comentario(doc_id,versao,paragrafo,pai,autor,autor_tipo,autor_ref,texto,sugestao,sugestao_estado,criado_em) "
                "VALUES(?,?,?,?,?,?,?,?,?,?,?)", (doc_id, versao, paragrafo, pai, ator["nome"], ator["tipo"], ator["ref"], texto, sugestao,
                                                   "pendente" if sugestao else None, agora))
            if pai:
                self.hub._db.execute("UPDATE doc_comentario SET estado='aberto', resolvido_por=NULL, resolvido_em=NULL WHERE id=? AND estado='resolvido' AND ?='convite'",
                                     (pai, ator["tipo"]))
            self.hub._db.commit()
        return {"ok": True, "id": cur.lastrowid}

    def _comentario(self, doc_id: str, cid) -> tuple | None:
        try:
            cid = int(cid)
        except (TypeError, ValueError):
            return None
        return self.hub._db.execute("SELECT id, autor_tipo, autor_ref, pai, apagado, sugestao, sugestao_estado, versao, paragrafo, estado "
                                    "FROM doc_comentario WHERE id=? AND doc_id=?", (cid, doc_id)).fetchone()

    def editar(self, doc_id: str, cid, ator: dict, texto: str) -> dict:
        texto = _limpo(texto, TEXTO_MAX)
        if not texto:
            return {"ok": False, "codigo": 400, "erro": "escreva o comentário"}
        with self.hub._trava:
            c = self._comentario(doc_id, cid)
            if not c or c[4]:
                return {"ok": False, "codigo": 404, "erro": "comentário não encontrado"}
            if (c[1], c[2]) != (ator["tipo"], ator["ref"]):
                return {"ok": False, "codigo": 403, "erro": "só quem escreveu edita"}
            self.hub._db.execute("UPDATE doc_comentario SET texto=?, editado_em=? WHERE id=?", (texto, self.hub.relogio(), c[0]))
            self.hub._db.commit()
        return {"ok": True}

    def apagar(self, doc_id: str, cid, ator: dict) -> dict:
        with self.hub._trava:
            c = self._comentario(doc_id, cid)
            if not c or c[4]:
                return {"ok": False, "codigo": 404, "erro": "comentário não encontrado"}
            if (c[1], c[2]) != (ator["tipo"], ator["ref"]) and not ator.get("direcao"):
                return {"ok": False, "codigo": 403, "erro": "só quem escreveu (ou a direção) apaga"}
            # some o texto; a conversa continua de pé para as respostas
            self.hub._db.execute("UPDATE doc_comentario SET texto='', sugestao=NULL, apagado=1, editado_em=? WHERE id=?", (self.hub.relogio(), c[0]))
            self.hub._db.commit()
        return {"ok": True}

    def resolver(self, doc_id: str, cid, ator: dict, resolvido: bool = True) -> dict:
        if ator.get("tipo") != "equipe":
            return {"ok": False, "codigo": 403, "erro": "só a equipe resolve"}
        with self.hub._trava:
            c = self._comentario(doc_id, cid)
            if not c:
                return {"ok": False, "codigo": 404, "erro": "comentário não encontrado"}
            if c[3]:
                return {"ok": False, "codigo": 400, "erro": "resolva a conversa pelo primeiro comentário"}
            agora = self.hub.relogio()
            if resolvido:
                self.hub._db.execute("UPDATE doc_comentario SET estado='resolvido', resolvido_por=?, resolvido_em=? WHERE id=?", (ator["nome"], agora, c[0]))
            else:
                self.hub._db.execute("UPDATE doc_comentario SET estado='aberto', resolvido_por=NULL, resolvido_em=NULL WHERE id=?", (c[0],))
            self.hub._db.commit()
        return {"ok": True}

    def sugestao(self, doc_id: str, cid, ator: dict, aceitar: bool) -> dict:
        """Aceitar: nova versão com o parágrafo trocado pelo texto sugerido e a conversa resolvida. Recusar: só marca."""
        if ator.get("tipo") != "equipe":
            return {"ok": False, "codigo": 403, "erro": "só a equipe decide sugestões"}
        with self.hub._trava:
            c = self._comentario(doc_id, cid)
            if not c or c[4] or not c[5]:
                return {"ok": False, "codigo": 404, "erro": "sugestão não encontrada"}
            if c[6] != "pendente":
                return {"ok": False, "codigo": 409, "erro": "esta sugestão já foi decidida"}
            res = {"ok": True}
            if aceitar:
                d = self.hub._db.execute("SELECT versao_atual FROM doc WHERE id=?", (doc_id,)).fetchone()
                html_atual = self.hub._db.execute("SELECT html FROM doc_versao WHERE doc_id=? AND versao=?", (doc_id, d[0])).fetchone()[0]
                limpo = sanitizar_html(html_atual, rebaixar_titulos=False, substituir={c[8]: c[5]})
                if c[8] not in limpo["trocados"]:
                    return {"ok": False, "codigo": 409, "erro": "o parágrafo não existe mais na versão atual; aplique à mão"}
                res = self.nova_versao(doc_id, ator, "", nota=f"Sugestão #{c[0]} aceita", _ja_limpo=limpo)
                if not res.get("ok"):
                    return res
            agora = self.hub.relogio()
            self.hub._db.execute("UPDATE doc_comentario SET sugestao_estado=?, estado='resolvido', resolvido_por=?, resolvido_em=? WHERE id=?",
                                 ("aceita" if aceitar else "recusada", ator["nome"], agora, c[0]))
            self.hub._db.commit()
        return dict(res, ok=True)

    # ── convites para quem revisa de fora ──
    def convidar(self, doc_id: str, ator: dict, d: dict, base: str = "") -> dict:
        if ator.get("tipo") != "equipe":
            return {"ok": False, "codigo": 403, "erro": "só a equipe convida"}
        nome = _limpo(d.get("nome"), 80)
        email = _limpo(d.get("email"), 160)
        if not nome:
            return {"ok": False, "codigo": 400, "erro": "falta o nome de quem vai revisar"}
        if email and not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
            return {"ok": False, "codigo": 400, "erro": "e-mail inválido"}
        try:
            dias = float(d.get("dias") or 7)
        except (TypeError, ValueError):
            return {"ok": False, "codigo": 400, "erro": "prazo inválido"}
        dias = max(1 / 24, min(DIAS_MAX, dias))
        token = secrets.token_urlsafe(32)
        with self.hub._trava:
            doc = self.hub._db.execute("SELECT arquivado FROM doc WHERE id=?", (doc_id,)).fetchone()
            if not doc:
                return {"ok": False, "codigo": 404, "erro": "documento não encontrado"}
            if doc[0] is not None:
                return {"ok": False, "codigo": 409, "erro": "documento arquivado"}
            agora = self.hub.relogio()
            cur = self.hub._db.execute("INSERT INTO doc_convite(doc_id,resumo,nome,email,pode_comentar,criado_por,criado_em,expira) VALUES(?,?,?,?,?,?,?,?)",
                                       (doc_id, seg.resumo(token), nome, email, 0 if d.get("pode_comentar") is False else 1, ator["ref"], agora, agora + dias * 86400))
            self.hub.registrar("documento", ator["ref"], {"o_que": "convite", "doc": doc_id[:8], "id": cur.lastrowid, "dias": round(dias, 2)})
            self.hub._db.commit()
        # o código vai depois do # : o navegador não o manda ao servidor, não fica em registro de acesso nem em Referer
        return {"ok": True, "id": cur.lastrowid, "expira": agora + dias * 86400, "token": token,
                "link": f"{base.rstrip('/')}/documento/{doc_id}#convite={token}",
                "aviso": "guarde o link agora: ele não aparece de novo"}

    def convites(self, doc_id: str) -> list[dict]:
        agora = self.hub.relogio()
        with self.hub._trava:
            linhas = self.hub._db.execute("SELECT id, nome, email, pode_comentar, criado_por, criado_em, expira, revogado, usado, acessos "
                                          "FROM doc_convite WHERE doc_id=? ORDER BY id", (doc_id,)).fetchall()
        return [{"id": i, "nome": n, "email": e, "pode_comentar": bool(pc), "criado_por": cp, "criado_em": ce, "expira": ex,
                 "revogado": rv, "usado": u, "acessos": a, "ativo": rv is None and ex > agora} for i, n, e, pc, cp, ce, ex, rv, u, a in linhas]

    def revogar(self, doc_id: str, cvid, ator: dict) -> dict:
        if ator.get("tipo") != "equipe":
            return {"ok": False, "codigo": 403, "erro": "só a equipe revoga"}
        try:
            cvid = int(cvid)
        except (TypeError, ValueError):
            return {"ok": False, "codigo": 404, "erro": "convite não encontrado"}
        with self.hub._trava:
            cur = self.hub._db.execute("UPDATE doc_convite SET revogado=? WHERE id=? AND doc_id=? AND revogado IS NULL", (self.hub.relogio(), cvid, doc_id))
            if not cur.rowcount:
                return {"ok": False, "codigo": 404, "erro": "convite não encontrado"}
            self.hub.registrar("documento", ator["ref"], {"o_que": "convite revogado", "doc": doc_id[:8], "id": cvid})
            self.hub._db.commit()
        return {"ok": True}

    def arquivar(self, doc_id: str, ator: dict, arquivado: bool = True) -> dict:
        if ator.get("tipo") != "equipe":
            return {"ok": False, "codigo": 403, "erro": "só a equipe arquiva"}
        with self.hub._trava:
            cur = self.hub._db.execute("UPDATE doc SET arquivado=? WHERE id=?", (self.hub.relogio() if arquivado else None, doc_id))
            if not cur.rowcount:
                return {"ok": False, "codigo": 404, "erro": "documento não encontrado"}
            self.hub._db.commit()
        return {"ok": True}

    def apagar_documento(self, doc_id: str, ator: dict) -> dict:
        """LGPD: apaga de vez o documento, as versões, os comentários e os convites (só a direção)."""
        if not ator.get("direcao"):
            return {"ok": False, "codigo": 403, "erro": "só a direção apaga documentos"}
        with self.hub._trava:
            cur = self.hub._db.execute("DELETE FROM doc WHERE id=?", (doc_id,))
            if not cur.rowcount:
                return {"ok": False, "codigo": 404, "erro": "documento não encontrado"}
            for t in ("doc_versao", "doc_comentario", "doc_convite"):
                self.hub._db.execute(f"DELETE FROM {t} WHERE doc_id=?", (doc_id,))
            self.hub.registrar("documento", ator["ref"], {"o_que": "apagado", "doc": doc_id[:8]})
            self.hub._db.commit()
        return {"ok": True}

    def retencao(self, dias: float | None = None) -> dict:
        """LGPD: passados `dias` (PHYSIS_DOC_RETENCAO_DIAS, padrão 180) do fim do convite, nome e e-mail do
        revisor externo viram "Revisor externo" (no convite e nos comentários). O texto do comentário fica."""
        if dias is None:
            try:
                dias = float(os.environ.get("PHYSIS_DOC_RETENCAO_DIAS") or 180)
            except ValueError:
                dias = 180.0
        limite = self.hub.relogio() - dias * 86400
        with self.hub._trava:
            ids = [r[0] for r in self.hub._db.execute(
                "SELECT id FROM doc_convite WHERE MIN(expira, COALESCE(revogado, expira)) < ? AND (email<>'' OR nome<>'Revisor externo')", (limite,))]
            for i in ids:
                self.hub._db.execute("UPDATE doc_convite SET nome='Revisor externo', email='' WHERE id=?", (i,))
                self.hub._db.execute("UPDATE doc_comentario SET autor='Revisor externo' WHERE autor_tipo='convite' AND autor_ref=?", (str(i),))
            self.hub._db.commit()
        return {"ok": True, "anonimizados": len(ids)}

    # ── rotas (o servidor chama; devolve (código, json) ou None se a rota não é daqui) ──
    def rota(self, metodo: str, caminho: str, conta: dict | None, corpo, convite: str | None = None,
             ip: str = "", base: str = "", consulta: dict | None = None):
        if not caminho.startswith("/api/documentos"):
            return None
        partes = [p for p in caminho.split("/") if p][2:]          # depois de /api/documentos
        try:
            d = seg.carregar_json((corpo.decode("utf-8", "replace") if isinstance(corpo, bytes) else corpo) or "{}") if metodo == "POST" else {}
        except ValueError:
            return 400, {"ok": False, "erro": "json invalido"}
        if not isinstance(d, dict):
            return 400, {"ok": False, "erro": "json invalido"}
        resp = lambda r: (r.pop("codigo", 200 if r.get("ok") else 400), r)
        if not partes:                                              # /api/documentos
            if not (conta and seg.pode(conta, seg.EQUIPE)):
                return (403, {"ok": False, "erro": "o seu papel não permite esta ação"}) if conta else (401, {"ok": False, "erro": "entre com usuario e senha", "login": True})
            ator = {"tipo": "equipe", "ref": conta["usuario"], "nome": conta.get("nome") or conta["usuario"], "direcao": seg.pode(conta, seg.DIRECAO), "pode_comentar": True}
            if metodo == "GET":
                return 200, {"ok": True, "documentos": self.listar()}
            if metodo == "POST":
                r = self.publicar(ator, d.get("titulo"), d.get("html"), d.get("origem", ""), d.get("nota", ""))
                if r.get("ok"):
                    r["link"] = base.rstrip("/") + r["link"]
                return resp(r)
            return 405, {"ok": False, "erro": "método não aceito"}
        doc_id = partes[0]
        if not _DOC_ID.match(doc_id):
            return 404, {"ok": False, "erro": "documento não encontrado"}
        ator, erro = self.ator(doc_id, conta, convite, ip)
        if erro:
            return erro
        resto = partes[1:]
        if metodo == "GET":
            if not resto:
                v = (consulta or {}).get("versao", [None])[0]
                try:
                    v = int(v) if v not in (None, "") else None
                except ValueError:
                    return 400, {"ok": False, "erro": "versão inválida"}
                return resp(self.ver(doc_id, ator, v))
            if resto == ["comentarios"]:
                return 200, {"ok": True, "comentarios": self.comentarios(doc_id, ator)}
            if resto == ["convites"]:
                if ator["tipo"] != "equipe":
                    return 403, {"ok": False, "erro": "só a equipe vê os convites"}
                return 200, {"ok": True, "convites": self.convites(doc_id)}
            return 404, {"ok": False, "erro": "rota desconhecida"}
        if metodo != "POST":
            return 405, {"ok": False, "erro": "método não aceito"}
        if resto == ["versoes"]:
            return resp(self.nova_versao(doc_id, ator, d.get("html"), d.get("nota", "")))
        if resto == ["comentarios"]:
            return resp(self.comentar(doc_id, ator, d))
        if len(resto) == 3 and resto[0] == "comentarios":
            cid, acao = resto[1], resto[2]
            if acao == "editar":
                return resp(self.editar(doc_id, cid, ator, d.get("texto")))
            if acao == "apagar":
                return resp(self.apagar(doc_id, cid, ator))
            if acao == "resolver":
                return resp(self.resolver(doc_id, cid, ator, d.get("resolvido", True) is not False))
            if acao == "sugestao":
                return resp(self.sugestao(doc_id, cid, ator, bool(d.get("aceitar"))))
        if resto == ["convites"]:
            r = self.convidar(doc_id, ator, d, base)
            return resp(r)
        if len(resto) == 3 and resto[0] == "convites" and resto[2] == "revogar":
            return resp(self.revogar(doc_id, resto[1], ator))
        if resto == ["arquivar"]:
            return resp(self.arquivar(doc_id, ator, d.get("arquivado", True) is not False))
        if resto == ["apagar"]:
            return resp(self.apagar_documento(doc_id, ator))
        return 404, {"ok": False, "erro": "rota desconhecida"}


# ── fontes da plataforma para a página do documento (tiradas do painel.html; nada vem da internet) ──
_FONTES_CACHE: dict = {}


def fontes_css(painel: Path | None = None, familias=("Fraunces", "Inter", "Lexend", "Atkinson Hyperlegible")) -> str:
    """@font-face das fontes embutidas no painel.html (data: woff2), para /documento/fontes.css."""
    painel = painel or (WEB / "painel.html")
    chave = (str(painel), painel.stat().st_mtime if painel.is_file() else 0)
    if chave in _FONTES_CACHE:
        return _FONTES_CACHE[chave]
    css = ""
    if painel.is_file():
        texto = painel.read_text(encoding="utf-8", errors="replace")
        blocos = re.findall(r"@font-face\{[^}]*\}", texto)
        css = "\n".join(b for b in blocos if any(f'font-family:"{f}"' in b or f"font-family:{f}" in b for f in familias))
    _FONTES_CACHE.clear()
    _FONTES_CACHE[chave] = css
    return css
